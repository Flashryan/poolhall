<?php
/**
 * Admin-owned approval gate for candidate terms.
 *
 * @package Poolhall\Integration
 */

declare(strict_types=1);

namespace Poolhall\Integration\Onboarding;

use Poolhall\Integration\Documents\DocumentWorkflow;
use Poolhall\Integration\Documents\FormDefinitions;
use Poolhall\Integration\Support\Logger;

/** Lets an authorised recruiter supply and explicitly approve legal copy. */
final class TermsSettings {

	private const CAP = 'manage_options';

	public function register(): void {
		add_action( 'admin_menu', array( $this, 'menu' ), 20 );
		add_action( 'admin_post_poolhall_save_candidate_terms', array( $this, 'save' ) );
	}

	public function menu(): void {
		add_submenu_page(
			'poolhall-candidates',
			'Candidate terms',
			TaskPolicy::archived( 'terms' ) ? 'Candidate terms (archived)' : 'Candidate terms',
			self::CAP,
			'poolhall-candidate-terms',
			array( $this, 'render' )
		);
	}

	public function render(): void {
		if ( ! current_user_can( self::CAP ) ) {
			return;
		}
		$text     = (string) get_option( 'poolhall_candidate_terms_text', '' );
		$version  = (string) get_option( 'poolhall_candidate_terms_version', '' );
		$approved = '1' === (string) get_option( 'poolhall_candidate_terms_approved', '' );
		$archived = TaskPolicy::archived( 'terms' );
		$saved    = isset( $_GET['terms_saved'] ) ? sanitize_key( wp_unslash( $_GET['terms_saved'] ) ) : ''; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- display-only redirect flag.

		echo '<div class="wrap"><h1>Candidate terms</h1>';
		if ( 'yes' === $saved ) {
			echo '<div class="notice notice-success is-dismissible"><p>Candidate terms settings saved.</p></div>';
		} elseif ( 'incomplete' === $saved ) {
			echo '<div class="notice notice-error"><p>Approval was not enabled because both the full legal wording and a version label are required.</p></div>';
		}
		echo $archived
			? '<p><strong>Candidate Terms is archived.</strong> It is excluded from candidate tasks, invitations, reminders and onboarding requirements. The form, wording and past submissions are retained.</p>'
			: '<p>Candidate Terms is active in onboarding. Approved wording and a version are required before it can be issued.</p>';
		echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '">';
		echo '<input type="hidden" name="action" value="poolhall_save_candidate_terms" />';
		wp_nonce_field( 'poolhall_save_candidate_terms' );
		echo '<table class="form-table" role="presentation"><tbody>';
		echo '<tr><th scope="row">Availability</th><td><label><input type="checkbox" name="terms_archived" value="1" ' . checked( $archived, true, false ) . ' /> Keep Candidate Terms archived</label><p class="description">Untick and save to restore this form to onboarding. Restoration still requires approved wording and a version.</p></td></tr>';
		echo '<tr><th scope="row"><label for="poolhall-terms-version">Version</label></th><td>';
		echo '<input class="regular-text" id="poolhall-terms-version" name="terms_version" value="' . esc_attr( $version ) . '" placeholder="For example: 2026-07 v1" /></td></tr>';
		echo '<tr><th scope="row"><label for="poolhall-terms-text">Approved wording</label></th><td>';
		echo '<textarea class="large-text" rows="22" id="poolhall-terms-text" name="terms_text">' . esc_textarea( $text ) . '</textarea>';
		echo '<p class="description">Paste the complete candidate contract/terms supplied or approved by Poolhall. No legal wording is generated by the website.</p></td></tr>';
		echo '<tr><th scope="row">Approval</th><td><label><input type="checkbox" name="terms_approved" value="1" ' . checked( $approved, true, false ) . ' /> ';
		echo 'I confirm Poolhall Recruitment has approved this exact version for candidates to sign.</label></td></tr>';
		echo '</tbody></table>';
		submit_button( 'Save candidate terms' );
		echo '</form>';
		if ( '' !== trim( $text ) ) {
			echo '<p><strong>Current SHA-256:</strong> <code>' . esc_html( hash( 'sha256', FormDefinitions::canonical_terms_text( $text ) ) ) . '</code></p>';
		}
		echo '</div>';
	}

	public function save(): never {
		if ( ! current_user_can( self::CAP ) ) {
			wp_die( 'Not allowed.' );
		}
		check_admin_referer( 'poolhall_save_candidate_terms' );

		$text      = isset( $_POST['terms_text'] ) ? sanitize_textarea_field( wp_unslash( $_POST['terms_text'] ) ) : '';
		$version   = isset( $_POST['terms_version'] ) ? sanitize_text_field( wp_unslash( $_POST['terms_version'] ) ) : '';
		$requested = isset( $_POST['terms_approved'] ) && '1' === sanitize_text_field( wp_unslash( $_POST['terms_approved'] ) );
		$approved  = $requested && '' !== trim( $text ) && '' !== trim( $version );
		$archived  = isset( $_POST['terms_archived'] ) && '1' === sanitize_text_field( wp_unslash( $_POST['terms_archived'] ) );

		update_option( 'poolhall_candidate_terms_text', $text, false );
		update_option( 'poolhall_candidate_terms_version', $version, false );
		update_option( 'poolhall_candidate_terms_approved', $approved ? '1' : '0', false );
		if ( $approved ) {
			$canonical = FormDefinitions::canonical_terms_text( $text );
			$hash      = hash( 'sha256', $canonical );
			$versions  = (array) get_option( 'poolhall_candidate_terms_versions', array() );
			$bucket    = isset( $versions[ $hash ] ) && is_array( $versions[ $hash ] ) ? $versions[ $hash ] : array();
			// Preserve snapshots written by the earlier flat hash => snapshot
			// shape before adding version as a second immutable key.
			if ( isset( $bucket['version'] ) ) {
				$legacy_version = (string) $bucket['version'];
				$bucket         = '' !== $legacy_version ? array( $legacy_version => $bucket ) : array();
			}
			$bucket[ $version ] = array(
				'version'      => $version,
				'text'         => $canonical,
				'display_text' => $text,
				'approved_at'  => gmdate( \DateTimeInterface::ATOM ),
			);
			$versions[ $hash ]  = $bucket;
			// Signed documents may refer to an older hash, so approved snapshots
			// are intentionally retained rather than overwritten or pruned.
			update_option( 'poolhall_candidate_terms_versions', $versions, false );
		}

		( new TermsArchive() )->set_archived( $archived );

		// Keep the managed Gravity Form's active state and immutable displayed
		// wording in step with the explicit approval decision.
		( new DocumentWorkflow( new Logger() ) )->setup_forms();

		$url = add_query_arg(
			'terms_saved',
			$requested && ! $approved ? 'incomplete' : 'yes',
			admin_url( 'admin.php?page=poolhall-candidate-terms' )
		);
		wp_safe_redirect( $url );
		exit;
	}
}
